import { cp, mkdir, rm, readdir, stat, writeFile, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { validateReleaseIdentity } from './manifest.mjs';
const manifest = validateReleaseIdentity(JSON.parse(await readFile('manifest.json', 'utf8')));
const directory = `dist/${manifest.id}`;
await rm('dist', { recursive: true, force: true });
await mkdir(directory, { recursive: true });
const required = ['main.js', 'manifest.json', 'styles.css'];
for (const name of required) await cp(name, `${directory}/${name}`);
const actual = (await readdir(directory)).sort();
if (actual.join(',') !== [...required].sort().join(',')) throw new Error('The installation must contain exactly the three Obsidian release files.');
const bytes = Object.fromEntries(await Promise.all(required.map(async name => [name, (await stat(`${directory}/${name}`)).size])));
await writeFile('dist/package-report.json', JSON.stringify({ id: manifest.id, version: manifest.version, files: bytes, total: Object.values(bytes).reduce((a,b) => a+b,0), offline: true, additionalRuntimeFiles: false }, null, 2));
execFileSync('zip', ['-q', '-r', 'MuseScorer.zip', manifest.id], { cwd: 'dist', stdio: 'inherit' });
console.log('Three-file installable archive: dist/MuseScorer.zip');
console.log(JSON.stringify(bytes));
