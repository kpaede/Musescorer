import { cp, mkdir, rm, readdir, stat, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
await rm('dist', { recursive: true, force: true });
await mkdir('dist/MuseScorer', { recursive: true });
const required = ['main.js', 'manifest.json', 'styles.css'];
for (const name of required) await cp(name, `dist/MuseScorer/${name}`);
const actual = (await readdir('dist/MuseScorer')).sort();
if (actual.join(',') !== [...required].sort().join(',')) throw new Error('The installation must contain exactly the three Obsidian release files.');
const bytes = Object.fromEntries(await Promise.all(required.map(async name => [name, (await stat(`dist/MuseScorer/${name}`)).size])));
await writeFile('dist/package-report.json', JSON.stringify({ files: bytes, total: Object.values(bytes).reduce((a,b) => a+b,0), offline: true, additionalRuntimeFiles: false }, null, 2));
execFileSync('zip', ['-q', '-r', 'MuseScorer.zip', 'MuseScorer'], { cwd: 'dist', stdio: 'inherit' });
console.log('Three-file installable archive: dist/MuseScorer.zip');
console.log(JSON.stringify(bytes));
